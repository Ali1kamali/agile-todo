export type TranslationKey = keyof typeof translations.fa

export function getTranslation(locale: Locale, key: TranslationKey, params?: Record<string, string | number>): string {
  let text = translations[locale][key] || translations.fa[key] || key
  if (params) {
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal))
    }
  }
  return text
}
